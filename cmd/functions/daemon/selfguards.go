// selfProtectSpec is one always-on guard over the daemon's own on-disk state.
type selfProtectSpec struct {
	path string
	mode guard.Mode
}

// selfProtectSpecs are the guards over the daemon's own state, independent of any [watch] section:
//
//	/etc/app-listener                 ModeReadOnly: all may read (daemon.conf stays world-readable), only the app-listener binary may modify (binaries.db, the binary ledger, included)
//	/etc/app-listener/fscrypt.key     ModeWhitelist, empty list: readable only by the app-listener binary
//	/etc/app-listener/edit-auth.hash  ModeWhitelist, empty list: sealed like the key so a non-app-listener root process can neither read it (offline crack) nor overwrite it (install its own password)
//
// guard_inodes holds one owner per inode, so the sealed files start BEFORE the directory: a live
// inner resource makes the directory's scans skip them (innerResourceOwnsLocked). Started after it,
// a sealed guard must prove its file's physical chain to take the row back, which fails under the
// bind mount systemd's ReadWritePaths=/etc/app-listener makes, leaving the key world-readable.
func selfProtectSpecs() []selfProtectSpec {
	return []selfProtectSpec{
		{fscrypt.MasterKeyFile, guard.ModeWhitelist},
		{editprotected.HashFile, guard.ModeWhitelist},
		{selfProtectDir, guard.ModeReadOnly},
	}
}

// sealed: the spec seals a secret (fscrypt.key, edit-auth.hash), so the daemon refuses to start
// without it rather than unlock vaults whose key any root process could read.
func (s selfProtectSpec) sealed() bool { return s.mode == guard.ModeWhitelist }

// selfSweepEvery is the self guards' inode-refresh interval, catching an fscrypt.key regenerated by
// `daemon --genkey` while running (a new inode the single-file guard would stop tracking). Matches
// the usecase sweep cadence.
const selfSweepEvery = 30 * time.Second

// selfGuards holds the always-on guards over the daemon's own on-disk state, outside the usecase's
// guard set: a reload never rebuilds them, so fscrypt.key and edit-auth.hash stay sealed through it.
// Every guard shares one LSM program set (guard/engine.go), so they cost resource slots, not links.
//
// The read-only directory guard is best effort: one that can't attach is logged and skipped. A
// sealed file's guard is not (selfProtectSpec.sealed).
type selfGuards struct {
	events chan usecase.DaemonEvent

	mu      sync.Mutex
	guards  []*guard.Guard
	stops   []chan struct{}
	stopped bool // detach() called; a concurrent attach() must bail
}

func newSelfGuards() *selfGuards {
	return &selfGuards{events: make(chan usecase.DaemonEvent, 256)}
}

// ensureHashFilePlaceholder makes sure editprotected.HashFile exists (even zero-length) before self
// guards attach, because:
//   - its dedicated guard is only created when the file ALREADY exists at attach time (the os.Stat
//     gate below), so a fresh install with no password would get none;
//   - once the /etc/app-listener ReadOnly guard is attached, its self-allow covers rewriting an
//     EXISTING entry but not creating one, so WriteHashFile's create-temp-then-rename was denied
//     when the daemon was already guarding its own directory.
//
// An empty placeholder made before any guard exists sidesteps both: the file always exists, so its
// ModeWhitelist guard (maskless self-allow, unaffected by the RO restriction) covers
// WriteHashFile's in-place rewrite. Zero length = "no password configured"
// (editprotected.HashFileExists/LoadHashFile treat empty as absent). No-op if /etc/app-listener
// doesn't exist or the file is there.
func ensureHashFilePlaceholder() error {
	if _, err := os.Stat(editprotected.HashFile); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return err
	}
	if _, statErr := os.Stat(selfProtectDir); statErr != nil {
		return nil //nolint:nilerr // no /etc/app-listener yet (nothing installed): nothing to bootstrap, not an error for the caller
	}
	f, err := os.OpenFile(editprotected.HashFile, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		if os.IsExist(err) {
			return nil
		}
		return err
	}
	return f.Close()
}

// Events is the merged denial stream from every attached self guard, tagged
// with the resource path (e.g. resource=/etc/app-listener). Never closed.
func (s *selfGuards) Events() <-chan usecase.DaemonEvent { return s.events }

// bootstrapSelfProtectPlaceholders pre-creates every file a later in-place-only write
// (ensureHashFilePlaceholder) needs BEFORE any self guard attaches: once the RO guard is live, the
// self binary can't create a new directory entry, only rewrite an existing one. Best-effort: a
// failure just means the real writer (WriteHashFile, writePinState) falls back to
// create-if-missing, which then races the RO guard.
func bootstrapSelfProtectPlaceholders() {
	if err := ensureHashFilePlaceholder(); err != nil {
		log.Warnf("daemon: self-protection: could not pre-create %s (%v) — setting an edit-protected password while the daemon runs may fail until it does", editprotected.HashFile, err)
	}
	if err := binledger.EnsurePlaceholders(binledger.DefaultPath); err != nil {
		log.Warnf("daemon: self-protection: could not pre-create %s (%v) — the binary ledger cannot be "+
			"written once /etc/app-listener is self-guarded", binledger.DefaultPath, err)
	}
	if err := ensurePinStateFilePlaceholder(); err != nil {
		log.Warnf("daemon: self-protection: could not pre-create %s (%v) — daemon --lockdown may not be able to recover this run's generation after a crash", pinStateFile, err)
	}
	if err := ensurePlaceholder(tempJournalFile); err != nil {
		log.Warnf("daemon: self-protection: could not pre-create %s (%v) — edit-protected --forward "+
			"grants will be refused", tempJournalFile, err)
	}
}

// attach builds and starts the self guards, pinned under pin.gen. Safe in its own goroutine: a
// racing detach() wins (attach stops what it built and returns). A spec path that doesn't exist
// (working-dir config, no system install) is skipped silently; the directory guard failing is
// logged and skipped; a sealed guard failing, or not owning its file's inode, is an error.
func (s *selfGuards) attach(pin pinCfg) error {
	s.mu.Lock()
	s.stopped = false
	s.mu.Unlock()

	bootstrapSelfProtectPlaceholders()

	self, err := ebpf.ComputeBinaryEntry("/proc/self/exe")
	if err != nil {
		return fmt.Errorf("self-protection: cannot resolve own executable: %w", err)
	}

	for _, spec := range selfProtectSpecs() {
		s.mu.Lock()
		bail := s.stopped
		s.mu.Unlock()
		if bail {
			return nil
		}
		if _, statErr := os.Stat(spec.path); statErr != nil {
			continue
		}
		g, gErr := startSelfGuard(spec, self, pin)
		if gErr != nil {
			if spec.sealed() {
				return gErr
			}
			log.Errorf("daemon: self-protection: CRITICAL: %v — it is writable by anything outside the "+
				"app-listener binary until the next restart; the daemon runs normally otherwise, config "+
				"protection is unaffected", gErr)
			continue
		}
		stop := make(chan struct{})

		s.mu.Lock()
		if s.stopped {
			s.mu.Unlock()
			close(stop)
			g.Stop()
			return nil
		}
		s.guards = append(s.guards, g)
		s.stops = append(s.stops, stop)
		s.mu.Unlock()

		go s.forward(spec.path, g, stop)
		log.Infof("daemon: self-protection: guarding %s", spec.path)
	}
	return nil
}

// startSelfGuard builds and starts spec's guard, stopping it again on any failure.
func startSelfGuard(spec selfProtectSpec, self guard.BinaryEntry, pin pinCfg) (*guard.Guard, error) {
	opts := append([]guard.GuardOption{
		guard.WithEagerPopulate(),
		// The daemon's own binary, uid-0 gated, every event: install /
		// --genkey / the binary ledger write these paths.
		guard.WithSelfAllowBinary(self, nil),
		// Do NOT widen the raw block-device gate to the rootfs device.
		guard.WithBackingDevices(nil),
		guard.WithPinning(pin.prefix("self:" + spec.path)),
	}, eventFilterOptions()...)
	g, err := guard.NewGuard(spec.path, spec.mode, nil, true, 0, opts...)
	if err != nil {
		return nil, fmt.Errorf("%s is NOT guarded: %w", spec.path, err)
	}
	if err := g.Start(); err != nil {
		g.Stop()
		return nil, fmt.Errorf("%s guard attached but its reader failed to start: %w", spec.path, err)
	}
	if spec.sealed() {
		owns, err := g.OwnsRootInode()
		if err == nil && !owns {
			err = errors.New("its inode is held by another resource")
		}
		if err != nil {
			g.Stop()
			return nil, fmt.Errorf("%s is NOT sealed: %w", spec.path, err)
		}
	}
	if pin.base != "" && g.PinDegraded() {
		log.Errorf("daemon: self-protection: CRITICAL: guard for %s could not pin its LSM links — it will not survive a SIGKILL", spec.path)
	}
	return g, nil
}

// startSelfGuards attaches the self guards, refusing startup (ErrCriticalStartup) when a sealed
// one can't be.
func startSelfGuards(pin pinCfg) (*selfGuards, error) {
	sg := newSelfGuards()
	if err := sg.attach(pin); err != nil {
		sg.detach()
		return nil, fmt.Errorf("%w: daemon: self-protection: %w", constants.ErrCriticalStartup, err)
	}
	return sg, nil
}

// detach stops every self guard and its forwarder, and makes any in-flight
// attach() bail. Idempotent.
func (s *selfGuards) detach() {
	s.mu.Lock()
	s.stopped = true
	guards, stops := s.guards, s.stops
	s.guards, s.stops = nil, nil
	s.mu.Unlock()

	for _, stop := range stops {
		close(stop)
	}
	for _, g := range guards {
		g.Stop()
	}
}

// forward tags one self guard's events with its resource path and merges them into s.events. Self
// guards have no whitelist or fscrypt lifecycle, so no binary re-sync; only a light inode sweep
// (picks up a regenerated fscrypt.key).
func (s *selfGuards) forward(resource string, g *guard.Guard, stop <-chan struct{}) {
	sweep := time.NewTicker(selfSweepEvery)
	defer sweep.Stop()
	for {
		select {
		case ev, ok := <-g.Events():
			if !ok {
				return
			}
			select {
			case s.events <- usecase.DaemonEvent{Resource: ev.ResourceLabel(resource), Event: ev}:
			case <-stop:
				return
			}
		case <-sweep.C:
			if err := g.SweepInodes(); err != nil {
				log.Warnf("daemon: self-protection: inode sweep for %s: %v", resource, err)
			}
		case <-stop:
			return
		}
	}
}

// mergeDaemonEvents fans the usecase and self-protection streams into one channel. Neither input is
// ever closed, so the forwarders live for the process lifetime.
func mergeDaemonEvents(srcs ...<-chan usecase.DaemonEvent) <-chan usecase.DaemonEvent {
	out := make(chan usecase.DaemonEvent, 512)
	for _, src := range srcs {
		go func(c <-chan usecase.DaemonEvent) {
			for ev := range c {
				out <- ev
			}
		}(src)
	}
	return out
}
